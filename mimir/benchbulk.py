"""One archive of all public benchmark blobs: `mimir bench publish-plan` writes it, and
`mimir fetch --bench-all` downloads that single file instead of hundreds of small ones.

The archive (`bulk/mimir-bench-all.tar.xz`) holds the staged `blobs/<ab>/<sha>.xz` files and the
`index/bench/` files, sorted, with zeroed owners and times, so the same input gives the same
bytes. Its sha256 and size are recorded in `bulk.toml` of the registry (copied from the staged
`index/bench/bulk.toml`); that committed record is the trust root. Unpacking keeps only blobs the
committed blob index lists as public, each checked (size, xz, sha256 of the content). Downloaded
data is untrusted: it is hashed and copied, never run."""

from __future__ import annotations

import hashlib
import io
import lzma
import os
import re
import tarfile
import tomllib
from dataclasses import dataclass
from pathlib import Path

from mimir import remote

BULK_FILE = "bulk/mimir-bench-all.tar.xz"
RECORD = "bulk.toml"
_BLOB = re.compile(r"blobs/([0-9a-f]{2})/([0-9a-f]{64})\.xz")
_INDEX_PREFIX = "index/bench/"


@dataclass(frozen=True)
class Bulk:
    file: str
    sha256: str
    size: int
    blobs: int


def build(stage: Path) -> Bulk:
    """Write the archive under `stage` from its `blobs/` and `index/bench/` files."""
    names = sorted(p.relative_to(stage).as_posix() for sub in ("blobs", "index/bench")
                   for p in (stage / sub).rglob("*") if p.is_file()
                   and p.name != "SHA256SUMS" and p.name != RECORD)
    buf = io.BytesIO()
    with tarfile.open(fileobj=buf, mode="w", format=tarfile.PAX_FORMAT) as tf:
        for name in names:
            data = (stage / name).read_bytes()
            ti = tarfile.TarInfo(name)
            ti.size, ti.mode, ti.mtime = len(data), 0o644, 0
            tf.addfile(ti, io.BytesIO(data))
    raw = lzma.compress(buf.getvalue(), format=lzma.FORMAT_XZ, check=lzma.CHECK_CRC64, preset=6)
    dest = stage / BULK_FILE
    dest.parent.mkdir(parents=True, exist_ok=True)
    part = dest.with_name(dest.name + ".part")
    part.write_bytes(raw)
    os.replace(part, dest)
    count = sum(1 for n in names if _BLOB.fullmatch(n))
    return Bulk(BULK_FILE, remote.sha256_path(dest), len(raw), count)


def record_text(bulk: Bulk) -> str:
    return ("# Generated by `mimir bench publish-plan`; copy to data/benchmarks/bulk.toml.\n"
            "[bulk]\n"
            f'file = "{bulk.file}"\nsha256 = "{bulk.sha256}"\nsize = {bulk.size}\n'
            f"blobs = {bulk.blobs}\n")


def load(idx: Path) -> Bulk:
    path = idx / RECORD
    if not path.is_file():
        raise remote.FetchError("no bulk archive is recorded in the registry (bulk.toml)")
    row = tomllib.loads(path.read_text(encoding="utf-8")).get("bulk", {})
    try:
        return Bulk(str(row["file"]), remote._hex(str(row["sha256"])), int(row["size"]),
                    int(row["blobs"]))
    except KeyError as exc:
        raise remote.FetchError(f"bulk.toml: missing {exc}") from exc


def _take(tf: tarfile.TarFile, ti: tarfile.TarInfo, ref: remote.BlobRef, dest: Path) -> None:
    if ti.size > ref.xz_bytes:
        raise remote.FetchError(f"bulk: {ti.name} is longer than the indexed {ref.xz_bytes}")
    src = tf.extractfile(ti)
    if src is None:
        raise remote.FetchError(f"bulk: {ti.name} cannot be read")
    data = src.read(ref.xz_bytes + 1)
    if len(data) != ref.xz_bytes:
        raise remote.FetchError(f"bulk: {ti.name}: {len(data)} bytes, index says {ref.xz_bytes}")
    raw = remote.unxz(data, ref.raw_bytes)
    if hashlib.sha256(raw).hexdigest() != ref.sha:
        raise remote.FetchError(f"bulk: {ti.name}: content does not match its name")
    dest.parent.mkdir(parents=True, exist_ok=True)
    part = dest.with_name(dest.name + ".part")
    part.write_bytes(data)
    os.replace(part, dest)


def unpack(archive: Path, idx: Path, cache: Path) -> tuple[int, int]:
    """Put each blob of the archive in `<cache>/blobs/<ab>/<sha>.xz` (where `fetch_blob` looks).
    Returns (written, already there). The `index/bench/` members are not used."""
    rows = remote.load_blob_index(idx)
    written = have = 0
    with tarfile.open(archive, "r|xz") as tf:
        for ti in tf:
            m = _BLOB.fullmatch(ti.name)
            if not ti.isreg() or (m is None and not ti.name.startswith(_INDEX_PREFIX)):
                raise remote.FetchError(f"bulk: refused member {ti.name!r}")
            if m is None:
                continue
            ref = rows.get(m.group(2))
            if ref is None or ref.visibility != "public":
                raise remote.FetchError(f"bulk: {ti.name} is not a public blob of the index")
            dest = cache / "blobs" / m.group(1) / f"{m.group(2)}.xz"
            if dest.is_file() and dest.stat().st_size == ref.xz_bytes:
                have += 1
                continue
            _take(tf, ti, ref, dest)
            written += 1
    return written, have


def fetch_all(idx: Path, loc: remote.Locations) -> tuple[int, int]:
    """Get the one archive (cache, `MIMIR_ARCHIVE`, then the URL) and unpack it into the cache."""
    bulk = load(idx)
    cached = loc.cache / "archives" / f"{bulk.sha256}-{Path(bulk.file).name}"
    if not cached.is_file():
        local = loc.archive_dir / bulk.file if loc.archive_dir else None
        if local is not None and local.is_file():
            remote.verified_archive(local, bulk.sha256, loc.cache)
            cached = local
        elif loc.data_url:
            remote.download(f"{loc.data_url.rstrip('/')}/{bulk.file}", cached, bulk.sha256,
                            bulk.size)
        else:
            raise remote.FetchError("no bulk archive here: use --online or set MIMIR_DATA_URL")
    return unpack(cached, idx, loc.cache)
