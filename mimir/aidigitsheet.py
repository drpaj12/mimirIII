"""One datasheet page per AI digit recognition design (markdown), generated from the store's
`aidigit_result` and `aidigit_null` rows. Nothing is typed by hand: every number is a column of a
row, every missing value shows its reason. Spec: docs/specs/2026-11-11-ai-digit-p6.md."""

from __future__ import annotations

from pathlib import Path
from typing import Any

Row = dict[str, Any]
NA = "n/a"
FAMILY_DOC = {"I1": "I1-TPU.md", "I3": "I3-DATAFLOW.md", "I4": "I4-FIXED.md",
              "I6": "I6-NEURALUT.md", "I7": "I7-BNN.md", "I8": "I8-TREELUT.md"}
INTERFACE = ("One top module `mnist_top`: `clk`, `rst`, `start`, `in_valid`, `in_data[7:0]` (one "
             "int8 pixel per transfer, 784 per image, valid/ready), `in_ready`, `done`, "
             "`pred[3:0]`, "
             "`scores[79:0]` (ten int8 scores). Verilog-2005, one clock, driven by the common "
             "testbench `tb/mnist_tb.v` (contract: `docs/INTERFACE.md`).")


def _f(v: Any, spec: str = "") -> str:
    if v is None:
        return NA
    if isinstance(v, int):
        return f"{v:,}"
    return format(v, spec or ",.1f")


def _line(label: str, value: str) -> str:
    return f"| {label} | {value} |"


def _qor(r: Row, nulls: dict[tuple[str, str, str], str]) -> list[str]:
    grid = NA if r.get("grid_w") is None else f"{r['grid_w']}x{r['grid_h']}"
    out = ["| Quantity | Value |", "|---|---|",
           _line("Grid (with IO ring)", grid),
           _line("Channel width W (routing and power)", _f(r.get("power_channel_width"))),
           _line("Minimum channel width", _f(r.get("area_min_chan_width"))),
           _line("LUT / FF / adder", " / ".join(_f(r.get(k)) for k in
                                                 ("area_lut", "area_ff", "area_adder"))),
           _line("CLB (use of the grid)",
                 f"{_f(r.get('area_clb'))} ({_f(r.get('clb_util_pct'))} %)"),
           _line("mult_36 / RAM blocks", f"{_f(r.get('area_mult36'))} / "
                 f"{_f(r.get('area_ram_blocks'))}"),
           _line("Wirelength", _f(r.get("area_wirelength"))),
           _line("Fmax (MHz) / critical path (ns)", f"{_f(r.get('speed_fmax_mhz'))} / "
                 f"{_f(r.get('speed_crit_path_ns'), ',.3f')}"),
           _line("Latency per image (us)", _f(r.get("speed_latency_us"))),
           _line("Power total / dynamic / static (mW)", " / ".join(
               _f(r.get(k)) for k in ("power_total_mw", "power_dynamic_mw", "power_static_mw"))),
           _line("Energy per image (uJ)", _f(r.get("energy_uj_per_img"), ",.3f"))]
    why = sorted({w for (d, t, f), w in nulls.items()
                  if d == r["design"] and t == r["target"] and f in ("area_lut", "power_total_mw")})
    return out + ([""] + [f"Not measured: {w}." for w in why] if why and r.get("area_lut") is None
                  else [])


def render(design: str, rows: list[Row], nulls: dict[tuple[str, str, str], str]) -> str:
    by = {r["target"]: r for r in rows}
    base = next(iter(by.values()))
    acc = base.get("acc_n")
    doc = FAMILY_DOC.get(base["impl_id"])
    out = [f"# Datasheet: {design}", "",
           "Generated by `mimir aidigit-table` from the Mimir store. Do not edit by hand.", "",
           "## Architecture", "",
           f"- Implementation: {base['impl_id']}, {base['arch_name']}.",
           f"- Setting (parameters): {base['setting']}.",
           f"- Model: {base['model_kind']}; accuracy reference: {base.get('acc_ref') or NA}.",
           (f"- Family document: `docs/{doc}`." if doc else "- Family document: none."),
           f"- Source: pin `{base.get('design_source')}`, commit "
           f"`{base.get('design_source_commit') or NA}`.", "",
           "## Interface", "", INTERFACE, "",
           "## Accuracy", "",
           "| Quantity | Value |", "|---|---|",
           _line("Tier / simulator", f"{base.get('acc_tier') or NA} / {base.get('acc_sim') or NA}"),
           _line("Images", _f(acc)),
           _line("Top-1 vs MNIST labels", NA if base.get("acc_top1") is None
                 else f"{base['acc_top1'] * 100:.2f} % ({_f(base.get('acc_label_correct'))})"),
           _line("Class match vs reference", f"{_f(base.get('acc_class_match'))} of {_f(acc)}"),
           _line("Score match vs reference", f"{_f(base.get('acc_score_match'))} of {_f(acc)}"),
           _line("Cycles per image", _f(base.get("speed_cycles_per_img"))),
           _line("Initialisation cycles (not in cycles per image)",
                 _f(base.get("speed_init_cycles"))), ""]
    for target, title in (("vtr-k6", "VTR k6, auto-sized grid"),
                          ("vtr-k6-fixed", "VTR k6, one fixed device (same grid and W for all)")):
        out += [f"## QoR: {title}", ""]
        out += _qor(by[target], nulls) if target in by else ["Not run for this design.", ""]
        out.append("")
    lpm = by.get("cyclonev-lpm")
    out += ["## Cyclone V (Odin III LPM netlist)", ""]
    out += (["| Cell | Count |", "|---|---|"] + [_line(n, _f(lpm.get(k))) for n, k in (
        ("lpm_mult", "lpm_mult"), ("lpm_add_sub", "lpm_add_sub"), ("lpm_compare", "lpm_compare"),
        ("altsyncram", "lpm_altsyncram"), ("scfifo", "lpm_scfifo"),
        ("netlist bytes", "netlist_bytes"))] if lpm else ["No LPM netlist row."])
    out += ["", "## Simulation status", "",
            "| Simulator | Result |", "|---|---|",
            _line("Verilator, RTL", f"{base.get('acc_tier') or NA} tier, {_f(acc)} images, "
                  f"class match {_f(base.get('acc_class_match'))}"),
            _line("Odin III `sim_tb`, RTL, quick tier", _odin(base, nulls))]
    vt = by.get("vtr-k6")
    if vt is not None and vt.get("acc_netlist_n") is not None:
        nm, nn = _f(vt.get("acc_netlist_class_match")), _f(vt.get("acc_netlist_n"))
        out.append(_line("Odin III `sim_tb`, LUT netlist", f"class match {nm} of {nn}"))
    out += ["", "## Provenance", "",
            f"- Odin III: {base.get('odin3_build') or NA}, "
            f"commit `{base.get('odin3_commit') or NA}`.",
            f"- Odin III simulation build: {base.get('odin_sim_build') or NA}.",
            f"- VTR commit: `{(vt or by.get('vtr-k6-fixed') or {}).get('vtr_commit') or NA}`; "
            f"architecture `{(vt or {}).get('arch_file') or NA}`.",
            f"- Generated RTL hash: {base.get('rtl_sha256') or NA}.",
            "- Result rows: " + ", ".join(f"`{r['origin']}`" for r in rows) + ".", ""]
    return "\n".join(out)


def _odin(base: Row, nulls: dict[tuple[str, str, str], str]) -> str:
    st = base.get("odin_sim_status")
    if st is None:
        return "not run"
    if st == "error":
        why = nulls.get((base["design"], base["target"], "odin_sim_n"), "no reason recorded")
        return f"error: {why}"
    n = base["odin_sim_n"]
    speed = base.get("odin_sim_cycles_per_s")
    return (f"{st}: class match {base['odin_sim_class_match']} of {n}, score match "
            f"{base['odin_sim_score_match']} of {n}; {_f(base.get('odin_sim_wall_s'))} s"
            + (f", {_f(speed)} cycles/s" if speed else ""))


def write_all(rows: list[Row], nulls: dict[tuple[str, str, str], str], out_dir: Path) -> dict[
        Path, str]:
    """The datasheet files by path: out_dir/datasheets/<design>.md."""
    designs = sorted({r["design"] for r in rows})
    return {out_dir / "datasheets" / f"{d}.md": render(
        d, [r for r in rows if r["design"] == d], nulls) for d in designs}
