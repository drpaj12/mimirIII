#!/usr/bin/env python3
"""Builds prog2.hexdump: a small hand-assembled Z80 program (loads, 8/16-bit ALU, DAA, rotates,
bit ops, stack, exchanges, block moves, IX/IY, calls/jumps, I/O, IM1 handler). 16 bytes per row."""

mem = bytearray(0x300)
lab = {}
fix = []
pc = 0


def org(a):
    global pc
    pc = a


def emit(*b):
    global pc
    for x in b:
        mem[pc] = x & 255
        pc += 1


def label(n):
    lab[n] = pc


def jr(op, n):
    emit(op, 0)
    fix.append((pc - 1, n, "r"))


def abs3(op, n):
    emit(op, 0, 0)
    fix.append((pc - 2, n, "a"))


def abs4(p, op, n):
    emit(p, op, 0, 0)
    fix.append((pc - 2, n, "a"))


org(0)
abs3(0xC3, "start")  # jp start
org(0x38)  # IM1 handler: bump counter at 0x2F0, print 'I'
emit(
    0xF5, 0xC5, 0x3A, 0xF0, 0x02, 0x3C, 0x32, 0xF0, 0x02
)  # push af; push bc; ld a,(2F0h); inc a; ld (2F0h),a
emit(0x3E, 0x49, 0x01, 0x00, 0x08, 0xED, 0x79)  # ld a,'I'; ld bc,0800h; out (c),a
emit(0xC1, 0xF1, 0xFB, 0xED, 0x4D)  # pop bc; pop af; ei; reti
org(0x66)
emit(
    0xF5, 0x3E, 0x4E, 0xD3, 0x08, 0xF1, 0xED, 0x45
)  # NMI: push af; ld a,'N'; out (8),a; pop af; retn
org(0x100)
label("start")
emit(0x31, 0x00, 0x03)  # ld sp,0300h
emit(0xED, 0x56, 0xFB)  # im 1; ei
# --- 8-bit loads and ALU
emit(
    0x3E, 0x5A, 0x06, 0xA5, 0x0E, 0x0F, 0x16, 0x80, 0x1E, 0x7F, 0x26, 0x02, 0x2E, 0x80
)  # ld a,b,c,d,e,h,l ,n
emit(
    0x78, 0x41, 0x4A, 0x53, 0x5C, 0x65, 0x6F, 0x7D
)  # ld a,b ; ld b,c ; ld c,d ; ... register-register
emit(
    0x77, 0x46, 0x70, 0x7E, 0x36, 0x3C, 0x34, 0x35, 0x86, 0x8E, 0x96, 0x9E
)  # ld (hl),a; ld b,(hl); ld (hl),b; ld a,(hl); ld (hl),n; inc/dec (hl); add/adc/sub/sbc a,(hl)
emit(0x80, 0x88, 0x90, 0x98, 0xA0, 0xA8, 0xB0, 0xB8)  # add/adc/sub/sbc/and/xor/or/cp b
emit(0xC6, 0x99, 0xCE, 0x01, 0xD6, 0x22, 0xDE, 0x05, 0xE6, 0x7F, 0xEE, 0x55, 0xF6, 0x80, 0xFE, 0x33)
emit(
    0x04, 0x05, 0x0C, 0x0D, 0x14, 0x15, 0x1C, 0x1D, 0x24, 0x25, 0x2C, 0x2D, 0x3C, 0x3D
)  # inc/dec r
emit(
    0x3E, 0x99, 0xC6, 0x01, 0x27, 0x2F, 0x37, 0x3F, 0xED, 0x44
)  # ld a,99h; add a,1; daa; cpl; scf; ccf; neg
emit(0x3E, 0x15, 0xC6, 0x27, 0x27, 0xD6, 0x44, 0x27)  # ld a,15h; add a,27h; daa; sub 44h; daa
emit(0x07, 0x0F, 0x17, 0x1F)  # rlca rrca rla rra
# --- CB group
emit(0xCB, 0x00, 0xCB, 0x09, 0xCB, 0x12, 0xCB, 0x1B, 0xCB, 0x24, 0xCB, 0x2D, 0xCB, 0x3F, 0xCB, 0x36)
emit(0xCB, 0x47, 0xCB, 0x7F, 0xCB, 0xC0, 0xCB, 0x80, 0xCB, 0xFE, 0xCB, 0xBE, 0xCB, 0x56, 0xCB, 0x06)
emit(0x21, 0x00, 0x02, 0x36, 0x5C, 0xED, 0x6F, 0xED, 0x67)  # ld hl,200h; ld (hl),5Ch; rld; rrd
# --- 16-bit
emit(
    0x01, 0x34, 0x12, 0x11, 0x78, 0x56, 0x21, 0xBC, 0x9A, 0x09, 0x19, 0x29, 0x39
)  # ld bc,de,hl,nn; add hl,bc/de/hl/sp
emit(
    0xED, 0x4A, 0xED, 0x52, 0xED, 0x5A, 0xED, 0x42, 0xED, 0x7A, 0xED, 0x72
)  # adc hl,bc; sbc hl,de; adc hl,de; sbc hl,bc; adc hl,sp; sbc hl,sp
emit(0x03, 0x13, 0x23, 0x33, 0x0B, 0x1B, 0x2B, 0x3B)  # inc/dec rr
emit(
    0x22,
    0x10,
    0x02,
    0x2A,
    0x10,
    0x02,
    0xED,
    0x43,
    0x12,
    0x02,
    0xED,
    0x5B,
    0x12,
    0x02,
    0xED,
    0x73,
    0x14,
    0x02,
    0xED,
    0x7B,
    0x14,
    0x02,
)
emit(
    0x32, 0x16, 0x02, 0x3A, 0x16, 0x02, 0x02, 0x0A, 0x12, 0x1A
)  # ld (nn),a; ld a,(nn); ld (bc),a; ld a,(bc); ld (de),a; ld a,(de)
# --- stack and exchanges
emit(0xC5, 0xD5, 0xE5, 0xF5, 0xC1, 0xD1, 0xE1, 0xF1)  # push bc,de,hl,af ; pop bc,de,hl,af
emit(0xEB, 0xD9, 0x08, 0xE3, 0xF9, 0x00)  # ex de,hl; exx; ex af,af'; ex (sp),hl; ld sp,hl
emit(0x31, 0x00, 0x03)
emit(0xD9, 0x08)  # restore shadow sets
# --- IX / IY
emit(0xDD, 0x21, 0x00, 0x02, 0xFD, 0x21, 0x20, 0x02)  # ld ix,200h ; ld iy,220h
emit(
    0xDD,
    0x36,
    0x03,
    0x77,
    0xDD,
    0x7E,
    0x03,
    0xFD,
    0x77,
    0x05,
    0xFD,
    0x46,
    0x05,
    0xDD,
    0x86,
    0x03,
    0xDD,
    0x34,
    0x03,
)
emit(
    0xDD,
    0xCB,
    0x03,
    0x06,
    0xFD,
    0xCB,
    0x05,
    0xC6,
    0xDD,
    0xE5,
    0xFD,
    0xE1,
    0xDD,
    0x09,
    0xFD,
    0x19,
    0xDD,
    0x23,
    0xFD,
    0x2B,
)
# --- block ops
emit(0x21, 0x00, 0x02, 0x11, 0x40, 0x02, 0x01, 0x08, 0x00, 0xED, 0xB0)  # ldir 8 bytes
emit(0x21, 0x00, 0x02, 0x01, 0x10, 0x00, 0x3E, 0x77, 0xED, 0xB1)  # cpir
emit(
    0x21,
    0x48,
    0x02,
    0x11,
    0x58,
    0x02,
    0x01,
    0x04,
    0x00,
    0xED,
    0xB8,
    0xED,
    0xA0,
    0xED,
    0xA8,
    0xED,
    0xA1,
    0xED,
    0xA9,
)  # lddr ldi ldd cpi cpd
# --- jumps, calls, loops
emit(0x06, 0x05)
label("dj")
emit(0x3C, 0x10)
fix.append((pc - 1, "dj", "r"))  # ld b,5 ; dj: inc a ; djnz dj
emit(0xAF)
jr(0x28, "z1")
emit(0x3E, 0xEE)
label("z1")  # xor a; jr z,z1 ; ld a,EE ; z1:
emit(0x3E, 0x01, 0xB7)
jr(0x20, "nz1")
emit(0x00)
label("nz1")
emit(0xB7)
abs3(0xCA, "jz1")
emit(0x00)
label("jz1")  # or a; jp z
emit(0x37)
abs3(0xDA, "jc1")
emit(0x00)
label("jc1")  # scf; jp c
abs3(0xCD, "sub1")
abs3(0xC3, "after")
label("sub1")
emit(0x3E, 0x42, 0xA7, 0xC0, 0xC8)  # ld a,42; and a; ret nz (not taken? and a -> nz so taken)
label("after")
emit(0xE7)  # rst 20h
abs3(0xC3, "io")
org(0x20)
emit(0x3E, 0x52, 0xC9)  # rst 20h: ld a,'R'; ret
org(0x1A0)
label("io")
# --- I/O
emit(
    0x3E, 0x41, 0xD3, 0x08, 0x01, 0x00, 0x08, 0xED, 0x41, 0xED, 0x78, 0xDB, 0x30, 0xED, 0x51
)  # out (8),a ; out (c),b ; in a,(c)...
emit(0x21, 0x00, 0x02, 0xED, 0xA3, 0xED, 0xA2, 0xED, 0xAB, 0xED, 0xAA)  # outi ini outd ind
emit(0x06, 0x03, 0x21, 0x00, 0x02, 0xED, 0xB3)  # otir
# --- spin writing a counter, giving interrupts a chance; ends with a loop
emit(0x3E, 0x30)
label("spin")
emit(0x3C, 0x32, 0xF1, 0x02, 0x00, 0xD3, 0x08)
jr(0x18, "spin")
for p, n, k in fix:
    t = lab[n]
    if k == "r":
        mem[p] = (t - (p + 1)) & 255
    else:
        mem[p] = t & 255
        mem[p + 1] = t >> 8
for i in range(0, 0x300, 16):
    print(" ".join(f"{b:02X}" for b in mem[i : i + 16]) + " ")
