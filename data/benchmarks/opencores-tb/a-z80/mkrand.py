#!/usr/bin/env python3
"""usage: mkrand.py <seed> : a 64 KiB RAM image holding a random straight-line Z80 program.
Address 0: register-initialising prologue; 0x38: IM1 interrupt handler; 0x66: NMI handler; 0x80..: ~12000 random
instructions drawn from templates (register loads, 8/16-bit ALU, rotates, CB bit ops, IX/IY with displacement,
exchanges, block ops with DE/HL pinned, RLD/RRD, IN/OUT (C), stores into 0x8000-0x83FF only), then JP 0x80.
Random instruction choice, not random bytes: every register/flag is defined before use, no jump leaves the program."""
import random, sys
r = random.Random(int(sys.argv[1]))
mem = [0x00] * 0x10000
def put(a, bs):
    for i, x in enumerate(bs): mem[a + i] = x
put(0, [0x31, 0x00, 0xC0, 0xAF, 0x01, 0x34, 0x12, 0x11, 0x78, 0x56, 0x21, 0xBC, 0x9A, 0x08, 0xAF, 0xD9,
        0x01, 0x11, 0x22, 0x11, 0x33, 0x44, 0x21, 0x55, 0x66, 0xD9, 0xDD, 0x21, 0x00, 0x80, 0xFD, 0x21, 0x00, 0x88,
        0x3E, 0x00, 0xED, 0x47, 0xED, 0x56, 0xFB, 0xC3, 0x80, 0x00])           # ... ld i,a ; im 1 ; ei ; jp 80h
put(0x38, [0xF5, 0xC5, 0x3E, 0x49, 0x01, 0x00, 0x08, 0xED, 0x79, 0xC1, 0xF1, 0xFB, 0xED, 0x4D])   # push af,bc; out 'I'; pop; ei; reti
put(0x66, [0xF5, 0x3E, 0x4E, 0xD3, 0x08, 0xF1, 0xED, 0x45])                                          # NMI: out 'N'; retn
R = [0, 1, 2, 3, 4, 5, 7]   # B C D E H L A (no (HL))
def rr(): return r.choice(R)
def idx(): return r.choice([0xDD, 0xFD])
def disp(): return r.randrange(0, 0x7F)
def addr(): return [r.randrange(256), 0x81 + r.randrange(3)]
def tmpl():
    k = r.randrange(26)
    if k == 0: return [0x40 | rr() << 3 | rr()]
    if k == 1: return [0x06 | rr() << 3, r.randrange(256)]
    if k == 2: return [0x80 | r.randrange(8) << 3 | rr()]
    if k == 3: return [0xC6 | r.randrange(8) << 3, r.randrange(256)]
    if k == 4: return [0x04 | rr() << 3 | r.randrange(2)]
    if k == 5: return [r.choice([0x03, 0x13, 0x23, 0x0B, 0x1B, 0x2B, 0x09, 0x19, 0x29, 0x39, 0x07, 0x0F, 0x17, 0x1F, 0x27, 0x2F, 0x37, 0x3F, 0xEB, 0xD9, 0x08, 0xE9 & 0 or 0x00])]
    if k == 6: return [0xED, r.choice([0x44, 0x4A, 0x5A, 0x6A, 0x7A, 0x42, 0x52, 0x62, 0x72, 0x57, 0x5F, 0x67, 0x6F][:11])] if False else [0xED, r.choice([0x44, 0x4A, 0x5A, 0x6A, 0x42, 0x52, 0x62])]
    if k == 7: return [0xCB, r.randrange(256) & ~7 | rr()]
    if k == 8: return [r.choice([0x01, 0x11, 0x21]), r.randrange(256), r.randrange(256)]
    if k == 9: return [idx(), 0x40 | rr() << 3 | 6, disp()] if r.random() < .5 else [idx(), 0x70 | rr(), disp()]
    if k == 10: return [idx(), r.choice([0x86, 0x8E, 0x96, 0x9E, 0xA6, 0xAE, 0xB6, 0xBE, 0x34, 0x35]), disp()]
    if k == 11: return [idx(), 0xCB, disp(), r.choice([0x06, 0x0E, 0x16, 0x1E, 0x26, 0x2E, 0x36, 0x3E, 0x46 | r.randrange(8) << 3, 0x86 | r.randrange(8) << 3, 0xC6 | r.randrange(8) << 3])]
    if k == 12: return [idx(), r.choice([0x21, 0x09, 0x19, 0x29, 0x23, 0x2B, 0xE5])] + ([r.randrange(256), r.randrange(256)] if True else []) if False else [idx(), r.choice([0x09, 0x19, 0x29, 0x23, 0x2B])]
    if k == 13: return [0xC5 | r.randrange(4) << 4, 0xC1 | r.randrange(4) << 4] if False else [0xC5, 0xD1] if r.random() < .5 else [0xF5, 0xE1]
    if k == 14: return [0x32] + addr() if r.random() < .5 else [0x3A] + addr()
    if k == 15: return [0x22] + addr() if r.random() < .5 else [0x2A] + addr()
    if k == 16: return [0xED, r.choice([0x43, 0x53, 0x63]) if r.random() < .5 else r.choice([0x4B, 0x5B, 0x6B])] + addr()
    if k == 17: return [0x11, 0x00, 0x82, 0xED, r.choice([0xA0, 0xA8])]
    if k == 18: return [0xED, r.choice([0xA1, 0xA9])]
    if k == 19: return [0x21, 0x00, 0x83, 0xED, r.choice([0x6F, 0x67])]
    if k == 20: return [0xED, 0x40 | rr() << 3 | r.randrange(2)] if False else [0xED, 0x40 | rr() << 3]
    if k == 21: return [0xED, 0x41 | rr() << 3]
    if k == 22: return [0xDD, r.choice([0x44, 0x45, 0x4C, 0x4D, 0x7C, 0x7D, 0x84, 0x85, 0x24, 0x2C, 0x26, 0x2E][:12])] if False else [idx(), r.choice([0x44, 0x45, 0x4C, 0x4D, 0x7C, 0x7D, 0x84, 0x85, 0x24, 0x2C])]
    if k == 23: return [0x3E, r.randrange(256), 0xED, 0x47]
    if k == 24: return [0x2A] + addr() if False else [0xF9 if False else 0x00]
    return [0xED, 0x57 if r.random() < .5 else 0x5F]
a = 0x80
for _ in range(12000):
    b = tmpl()
    if a + len(b) > 0x7000: break
    put(a, b); a += len(b)
put(a, [0xC3, 0x80, 0x00])
for i in range(0, 0x10000, 16): print(' '.join('%02X' % x for x in mem[i:i+16]) + ' ')
