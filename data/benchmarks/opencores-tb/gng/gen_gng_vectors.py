"""Golden vectors and the coefficient ROM for the OpenCores gng testbench.

tb_origin: mimir-written / upstream-fixed (see README.md). Python port of the project's own C model
(c/taus176.c, c/icdf.c of OpenCores gng, LGPL 2.1 or later). The coefficient tables C0, C1, C2 are
read from the upstream icdf.c given on the command line (nothing is typed in here); they are written
as the synchronous ROM `gng_coef.v` the project does not ship (it was a vendor-generated core).

    python3 gen_gng_vectors.py <path-to-gng/c/icdf.c> <output-dir>

Deterministic: fixed seeds, no clock, no random module.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

M64 = (1 << 64) - 1
INIT_Z = (5030521883283424767, 18445829279364155008, 18436106298727503359)
STREAM_N = 8192
LCG_A = 6364136223846793005
LCG_C = 1442695040888963407


def parse_tables(icdf_c: str) -> dict[str, list[int]]:
    """Read the C0, C1, C2 arrays from the text of the upstream icdf.c."""
    out: dict[str, list[int]] = {}
    for name in ("C0", "C1", "C2"):
        m = re.search(rf"static const long {name}\[(\d+)\] = \{{(.*?)\}};", icdf_c, re.S)
        if m is None:
            raise ValueError(f"table {name} not found")
        vals = [int(v) for v in re.findall(r"-?\d+", m.group(2))]
        if len(vals) != int(m.group(1)):
            raise ValueError(f"table {name}: {len(vals)} values, declared {m.group(1)}")
        out[name] = vals
    return out


def taus_get(z: list[int]) -> int:
    """One step of taus176.c taus_get on the state list [z1, z2, z3]; returns z1^z2^z3."""
    b = (((z[0] << 5) & M64) ^ z[0]) >> 39
    z[0] = (((z[0] & 18446744073709551614) << 24) & M64) ^ b
    b = (((z[1] << 19) & M64) ^ z[1]) >> 45
    z[1] = (((z[1] & 18446744073709551552) << 13) & M64) ^ b
    b = (((z[2] << 24) & M64) ^ z[2]) >> 48
    z[2] = (((z[2] & 18446744073709551104) << 7) & M64) ^ b
    return z[0] ^ z[1] ^ z[2]


def icdf(n: int, t: dict[str, list[int]]) -> int:
    """Port of icdf.c icdf(): a 64-bit uniform word to a signed s<16,11> integer."""
    tmp = n
    num_lzd = 0
    for _ in range(61):
        if tmp & (1 << 63):
            break
        num_lzd += 1
        tmp = (tmp << 1) & M64
    addr = num_lzd << 2
    if n & 2:
        addr += 2
    if n & 4:
        addr += 1
    c0, c1, c2 = t["C0"][addr], t["C1"][addr], t["C2"][addr]
    if num_lzd <= 60:
        n &= ~(1 << (63 - num_lzd)) & M64
    tmp = n >> 3
    x = 0
    for _ in range(15):
        x = (x << 1) | (tmp & 1)
        tmp >>= 1
    y = c2 * x
    y += c1 << 19
    y >>= 20
    y *= x
    y >>= 19
    y += c0
    carry = 1 if (y & 4) else 0
    y >>= 3
    y += carry
    return -y if (n & 1) else y


def stream(t: dict[str, list[int]], count: int) -> list[int]:
    """The first `count` noise samples of the core with the testbench's initial state."""
    z = list(INIT_Z)
    return [icdf(taus_get(z), t) for _ in range(count)]


def interp_inputs() -> tuple[list[int], list[int]]:
    """Directed 64-bit words and a check flag for each.

    Every leading-zero count 0..61, offset 0..3, sign 0..1, 3 low-bit patterns. The leading one
    sits at bit 63-lz (none for lz = 61); the bits below it come from a fixed LCG. Each
    leading-zero group starts with a warm-up copy of its first word, flagged 0 (reported, not
    checked): gng_interp.v applies the x mask one clock late, so the first word after a change of
    leading-zero count is masked with the previous word's mask (see README.md). Every other word
    is flagged 1.
    """
    words: list[int] = []
    flags: list[int] = []
    state = 12345
    for lz in range(62):
        group_start = len(words)
        for off in range(4):
            for sign in range(2):
                for variant in range(3):
                    state = (state * LCG_A + LCG_C) & M64
                    low = state
                    if variant == 1:
                        low = 0
                    elif variant == 2:
                        low = M64
                    if lz <= 60:
                        below = (1 << (63 - lz)) - 1
                        w = (1 << (63 - lz)) | (low & below)
                    else:
                        w = low & 7
                    w = (w & ~7) | sign | (2 if off & 2 else 0) | (4 if off & 1 else 0)
                    if len(words) == group_start:
                        words.append(w)
                        flags.append(0)
                    words.append(w)
                    flags.append(1)
    return words, flags


def rom_verilog(t: dict[str, list[int]]) -> str:
    """The synchronous ROM gng_coef: 256 words, addresses 248..255 (never reached) read 0."""
    lines = [
        "// Generated by gen_gng_vectors.py from the C0, C1, C2 tables of OpenCores gng c/icdf.c.",
        "// Behavioural replacement for the vendor-generated gng_coef core (not in the project).",
        "// c0 u<18,14>, c1 s<18,19> two's complement, c2 u<17,23>; synchronous read, one cycle.",
        "`timescale 1 ns / 1 ps",
        "module gng_coef (",
        "    input clk,",
        "    input [7:0] addr,",
        "    output reg [17:0] c0,",
        "    output reg [17:0] c1,",
        "    output reg [16:0] c2",
        ");",
        "always @ (posedge clk) begin",
        "    case (addr)",
    ]
    for a in range(248):
        c0, c1, c2 = t["C0"][a], t["C1"][a], t["C2"][a]
        if not (0 <= c0 < 1 << 18 and -(1 << 17) <= c1 < 1 << 17 and 0 <= c2 < 1 << 17):
            raise ValueError(f"coefficient out of range at {a}")
        lines.append(
            f"        8'd{a}: begin c0 <= 18'd{c0}; c1 <= 18'h{c1 & 0x3FFFF:05x}; "
            f"c2 <= 17'd{c2}; end"
        )
    lines += [
        "        default: begin c0 <= 18'd0; c1 <= 18'd0; c2 <= 17'd0; end",
        "    endcase",
        "end",
        "endmodule",
        "",
    ]
    return "\n".join(lines)


def build(icdf_c: str) -> dict[str, str]:
    """All generated files as name -> text."""
    t = parse_tables(icdf_c)
    words, flags = interp_inputs()
    return {
        "gng_coef.v": rom_verilog(t),
        "stream_exp.hex": "".join(f"{v & 0xFFFF:04x}\n" for v in stream(t, STREAM_N)),
        "interp_in.hex": "".join(f"{w:016x}\n" for w in words),
        "interp_exp.hex": "".join(f"{icdf(w, t) & 0xFFFF:04x}\n" for w in words),
        "interp_chk.hex": "".join(f"{f:x}\n" for f in flags),
    }


def main(argv: list[str]) -> int:
    if len(argv) != 3:
        print(__doc__)
        return 2
    files = build(Path(argv[1]).read_text(encoding="utf-8", errors="replace"))
    out = Path(argv[2])
    out.mkdir(parents=True, exist_ok=True)
    for name, text in files.items():
        (out / name).write_text(text, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
