"""I8: train an XGBoost model on the testbench's int8 pixels, convert with TreeLUT (read by path),
generate Verilog + our `mnist_top` wrapper + model vectors.

usage: treelut_gen.py <setting> <build_dir> [--tiers quick,full]
Runs in the nnlut venv. Settings: lutnn_common.TREE_SETTINGS. Writes into <build_dir>
(never committed):
  treelut_all.v   TreeLUT's generated modules, one file
  mnist_top.v     our wrapper (feature ladder, compact feature buffer, TreeLUT, argmax, done)
  vec/<tier>/     vec_*.hex whose golden is THIS model (class + low byte of each class sum)
  gen.json        accuracies and sha256
Feature = clip(round((q + 19) * (2^w - 1) / 146), 0, 2^w - 1) of the streamed int8 pixel q
(19 and 146 = the range of q over MNIST: q(p=0) = -19, q(p=255) = 127). One global map for all
pixels (TreeLUT's own example uses a per-pixel MinMaxScaler on the raw 0..255 pixel; the
testbench streams q, so the map is on q).
"""

import argparse
import importlib
import json
import os
import sys
import time
from pathlib import Path

import numpy as np

sys.dont_write_bytecode = True
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
LC = importlib.import_module("lutnn_common")

QMIN, QSPAN = -19, 146


def feature_map(q, w):
    m = (1 << w) - 1
    return np.clip(np.round((q.astype(np.float64) - QMIN) * m / QSPAN), 0, m).astype(np.int64)


def ladder(w):
    """tu[k-1] = smallest u = q + 128 (q in -127..127) with feature >= k; asserts monotone."""
    qs = np.arange(-127, 128)
    f = feature_map(qs, w)
    assert (np.diff(f) >= 0).all()
    out = []
    for k in range(1, 1 << w):
        idx = np.nonzero(f >= k)[0]
        out.append(int(idx[0]) + 1 if len(idx) else 256)  # u = idx + 1
    return out


def sums_model(clf, x):
    """Per-class sums of the converted model (int), (n, classes). Uses TreeLUT's own tree walker."""
    nc = clf._n_classes
    trees = []
    for t in clf._treelut_model:
        a = np.zeros((len(t), 6), dtype=int)
        for j, nd in t.items():
            a[j, 0] = j
            if nd["type"] == "leaf":
                a[j, 1], a[j, 3] = 1, nd["value"]
            else:
                a[j, 2], a[j, 3], a[j, 4], a[j, 5] = (
                    nd["feature"],
                    nd["threshold"],
                    nd["yes"],
                    nd["no"],
                )
        trees.append(a)
    s = np.zeros((len(x), nc), dtype=np.int64)
    for c in range(nc):
        s[:, c] = clf._classes_bias[c]
    for i, a in enumerate(trees):
        s[:, i % nc] += clf._single_tree_predict(a, x)
    return s


def wrapper_verilog(w, tu, used, latency, sum_bits, pipelined):
    ranks, k = {}, 0
    for j in range(784):
        if used[j]:
            ranks[j] = k
            k += 1
    nu = k
    L = []
    p = L.append
    p("// Generated by tools/treelut_gen.py (do not edit). I8 TreeLUT wrapper (P0 interface).")
    p("module mnist_top (input clk, input rst, input start, input in_valid, input [7:0] in_data,")
    p("                  output in_ready, output reg done, output reg [3:0] pred,")
    p("                  output reg [79:0] scores);")
    p(f"  localparam NU = {nu};   // pixels some tree reads; the others are not stored")
    p(f"  localparam W = {w};")
    p("  reg loading;")
    p("  reg [9:0] cnt;")
    p("  reg waiting;")
    p("  reg [3:0] wcnt;")
    p(f"  reg [{max(nu * w, 1) - 1}:0] sh;")
    p("  assign in_ready = loading;")
    p("  reg use_r;")
    p("  always @(cnt) begin")
    p("    use_r = 1'b0;")
    p("    case (cnt)")
    for j in range(784):
        if used[j]:
            p(f"      10'd{j}: use_r = 1'b1;")
    p("      default: use_r = 1'b0;")
    p("    endcase")
    p("  end")
    p("  wire [7:0] u = in_data ^ 8'h80;   // q + 128, unsigned order-preserving")
    expr = f"{w}'d0"
    for kk in range(1, 1 << w):
        expr = f"((u >= 8'd{tu[kk - 1]}) ? {w}'d{kk} : " + expr + ")" if tu[kk - 1] < 256 else expr
    p(f"  wire [W-1:0] feat = {expr};")
    p(f"  wire [{784 * w - 1}:0] I;")
    for j in range(784):
        if used[j]:
            hi = (nu - 1 - ranks[j]) * w + w - 1
            lo = (nu - 1 - ranks[j]) * w
            p(f"  assign I[{(j + 1) * w - 1}:{j * w}] = sh[{hi}:{lo}];")
        else:
            p(f"  assign I[{(j + 1) * w - 1}:{j * w}] = {w}'d0;")
    p(f"  wire [{10 * sum_bits - 1}:0] O;")
    p("  TreeLUT core (" + (".clk(clk), " if pipelined else "") + ".i(I), .o(O));")
    for kk in range(10):
        p(f"  wire [{sum_bits - 1}:0] s{kk} = O[{kk * sum_bits + sum_bits - 1}:{kk * sum_bits}];")
    p(f"  wire [{sum_bits - 1}:0] v0 = s0;")
    p("  wire [3:0] b0 = 4'd0;")
    for kk in range(1, 10):
        p(f"  wire g{kk} = (s{kk} > v{kk - 1});")
        p(f"  wire [{sum_bits - 1}:0] v{kk} = g{kk} ? s{kk} : v{kk - 1};")
        p(f"  wire [3:0] b{kk} = g{kk} ? 4'd{kk} : b{kk - 1};")
    p("  always @(posedge clk) begin")
    p("    if (rst) begin")
    p("      loading <= 1'b0; cnt <= 10'd0; waiting <= 1'b0; wcnt <= 4'd0; done <= 1'b0;")
    p("      pred <= 4'd0; scores <= 80'd0; sh <= 0;")
    p("    end else begin")
    p("      if (start) begin loading <= 1'b1; cnt <= 10'd0; done <= 1'b0; waiting <= 1'b0; end")
    p("      else if (loading && in_valid) begin")
    p(f"        if (use_r) sh <= {{sh[{max(nu * w, 2) - 1 - w}:0], feat}};")
    p("        cnt <= cnt + 10'd1;")
    p("        if (cnt == 10'd783) begin loading <= 1'b0; waiting <= 1'b1; wcnt <= 4'd0; end")
    p("      end else if (waiting) begin")
    p(f"        if (wcnt == 4'd{latency}) begin")
    p("          waiting <= 1'b0; done <= 1'b1; pred <= b9;")
    for kk in range(10):
        low = f"s{kk}[7:0]" if sum_bits >= 8 else f"{{{8 - sum_bits}'d0, s{kk}}}"
        p(f"          scores[{8 * kk + 7}:{8 * kk}] <= {low};")
    p("        end else wcnt <= wcnt + 4'd1;")
    p("      end")
    p("    end")
    p("  end")
    p("endmodule")
    return "\n".join(L) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("setting")
    ap.add_argument("build_dir")
    ap.add_argument("--tiers", default="quick,full")
    ap.add_argument("--threads", type=int, default=4)
    a = ap.parse_args()
    from treelut import TreeLUTClassifier
    from xgboost import XGBClassifier

    s = LC.TREE_SETTINGS[a.setting]
    os.makedirs(a.build_dir, exist_ok=True)
    wf = s["treelut"]["w_feature"]
    qtr, ytr = LC.load("train")
    qte, yte = LC.load("test")
    xtr, xte = feature_map(qtr, wf), feature_map(qte, wf)
    info = {"setting": a.setting, "xgb": s["xgb"], "treelut": s["treelut"]}
    t0 = time.time()
    xgb = XGBClassifier(**s["xgb"], n_jobs=a.threads, random_state=0)
    xgb.fit(xtr, ytr)
    info["xgb_train_s"] = round(time.time() - t0, 1)
    info["xgb_top1"] = 100.0 * float((xgb.predict(xte) == yte).mean())
    tl = TreeLUTClassifier(xgb_model=xgb, dir_path=os.path.join(a.build_dir, "tl"), **s["treelut"])
    tl.convert()
    sums = sums_model(tl, xte)
    cls = np.argmax(sums, axis=1)
    info["treelut_model_top1"] = 100.0 * float((cls == yte).mean())
    info["treelut_predict_agrees"] = int((tl.predict(xte) == cls).sum())
    tl.verilog()
    vdir = os.path.join(a.build_dir, "tl", "TreeLUT", "verilog")
    files = sorted(os.listdir(vdir))
    bd = Path(a.build_dir)
    with open(bd / "treelut_all.v", "w") as out:
        for f in files:
            out.write((Path(vdir) / f).read_text() + "\n")
    used_features = sorted(
        {
            int(f)
            for t in tl._treelut_model
            for d in t.values()
            if "feature" in d
            for f in [d["feature"]]
        }
    )
    used = [j in set(used_features) for j in range(784)]
    pipe = s["treelut"]["pipeline"]
    latency = int(sum(pipe))
    info["pixels_used"] = int(sum(used))
    info["latency_cycles"] = latency
    info["sum_bits"] = int(tl._sum_bit_length)
    info["unique_features"] = len(tl._extract_unique_features())
    tu = ladder(wf)
    (bd / "mnist_top.v").write_text(
        wrapper_verilog(wf, tu, used, latency, int(tl._sum_bit_length), any(pipe))
    )
    for t, n in (("quick", 100), ("full", 10000)):
        if t in a.tiers.split(","):
            c = LC.write_vectors(bd / "vec" / t, n, qte, yte, cls, sums & 0xFF)
            info[f"model_label_correct_{t}"] = c
    info["sha256"] = {
        f: LC.sha256_file(f"{a.build_dir}/{f}") for f in ("treelut_all.v", "mnist_top.v")
    }
    text = json.dumps(info, indent=1, sort_keys=True, default=str)
    (bd / "gen.json").write_text(text)
    print(text)


if __name__ == "__main__":
    main()
