"""Generate the C weight file of the soft-CPU implementations (I2) from the golden network.

usage: gen_sw_weights.py <transmission.bin> <out_weights.c>
Writes const int8_t arrays in the layout sw/lenet.c reads (conv: [oc][c][ky][kx]; fc: [out][in]),
the per-layer requant (M0, n) as macros, and the quarter-square table. Generated at build time
into the build directory; the weights are never committed.
"""
import importlib
import sys
from pathlib import Path

sys.dont_write_bytecode = True
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
Net = importlib.import_module("golden.lenet_int8").Net

NAMES = ["conv1", "conv2", "fc1", "fc2", "fc3"]


def arr(name, flat):
    rows = []
    for i in range(0, len(flat), 24):
        rows.append(" " + ",".join(str(int(v)) for v in flat[i:i + 24]) + ",")
    return f"const int8_t W_{name}[{len(flat)}] = {{\n" + "\n".join(rows) + "\n};\n"


def main(bin_path, out):
    net = Net(bin_path, 0.02268019)
    t = ["/* generated by tools/gen_sw_weights.py from LeNet_5_TRANSMISSION.bin: do not commit */",
         "#include <stdint.h>", '#include "weights.h"']
    for k in NAMES:
        t.append(arr(k.upper(), net.w[k].reshape(-1)))
    t.append("const uint16_t QSQ[257] = {")
    t.append(" " + ",".join(str((x * x) // 4) for x in range(257)) + "\n};")
    Path(out).write_text("\n".join(t) + "\n")
    h = ["/* generated: requant constants and weight arrays */", "#include <stdint.h>"]
    for k in NAMES:
        m0, n = net.q[k]
        h.append(f"#define M0_{k.upper()} {m0}\n#define N_{k.upper()} {n}")
        h.append(f"extern const int8_t W_{k.upper()}[{net.w[k].size}];")
    h.append("extern const uint16_t QSQ[257];")
    Path(out).with_name("weights.h").write_text("\n".join(h) + "\n")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
